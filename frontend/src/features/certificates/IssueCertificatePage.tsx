import { useEffect, useRef, useState } from 'react'
import { zodResolver } from '@hookform/resolvers/zod'
import { CheckCircle2, Download, ExternalLink, FilePlus2, Info } from 'lucide-react'
import { useForm } from 'react-hook-form'
import { Link } from 'react-router-dom'

import { Alert } from '@/components/feedback/Alert'
import { CopyButton } from '@/components/feedback/CopyButton'
import { StatusBadge } from '@/components/certificates/StatusBadge'
import { Button } from '@/components/ui/Button'
import { Card, CardHeader, PageHeader } from '@/components/ui/Card'
import { Field, Input } from '@/components/ui/Field'
import { useCreateCertificate, useDownload } from '@/features/certificates/hooks'
import { issueDefaults, issueFieldNames, issueSchema, toCreateInput, type IssueFormValues } from '@/features/certificates/issueSchema'
import { ApiError, describeError } from '@/lib/apiClient'
import { formatDate } from '@/lib/utils'
import type { CertificateCreated } from '@/types/certificate'

const ORG_KEY = 'certitrust.lastOrganization'

function readLastOrg(): string {
  try {
    return window.localStorage.getItem(ORG_KEY) ?? ''
  } catch {
    return ''
  }
}
function saveLastOrg(value: string) {
  try {
    window.localStorage.setItem(ORG_KEY, value)
  } catch {
    /* storage unavailable: ignore */
  }
}

export function IssueCertificatePage() {
  const mutation = useCreateCertificate()
  const { download, pendingId } = useDownload()
  const [created, setCreated] = useState<CertificateCreated | null>(null)
  const submitting = useRef(false)
  const {
    register,
    handleSubmit,
    reset,
    setError,
    setFocus,
    formState: { errors },
  } = useForm<IssueFormValues>({ resolver: zodResolver(issueSchema), defaultValues: { ...issueDefaults, organization_name: readLastOrg() } })

  useEffect(() => {
    document.title = 'Issue certificate – CertiTrust'
  }, [])

  function onSubmit(values: IssueFormValues) {
    if (submitting.current || mutation.isPending) return // prevent duplicate submits
    submitting.current = true
    mutation.mutate(toCreateInput(values), {
      onSuccess: (result) => {
        saveLastOrg(values.organization_name)
        setCreated(result)
      },
      onError: (error) => {
        if (error instanceof ApiError && error.status === 422) {
          let first: keyof IssueFormValues | null = null
          for (const detail of error.details) {
            const name = detail.field?.split(/[.>\s[\]]+/).filter(Boolean).pop()
            if (name && (issueFieldNames as string[]).includes(name)) {
              setError(name as keyof IssueFormValues, { message: detail.message ?? 'This value is not valid.' })
              first ??= name as keyof IssueFormValues
            }
          }
          if (first) setFocus(first)
        }
      },
      onSettled: () => {
        submitting.current = false
      },
    })
  }

  if (created) {
    return (
      <div>
        <PageHeader title="Certificate issued" />
        <Card>
          <div className="flex items-start gap-3 border-b border-emerald-200 bg-emerald-50 p-5 text-emerald-900" role="status">
            <CheckCircle2 className="mt-0.5 size-6 shrink-0" aria-hidden="true" />
            <div>
              <h2 className="text-lg font-bold">The certificate was created and signed</h2>
              <p className="text-sm">The PDF and its digital signatures were generated by the server for {created.certificate.recipient_name}.</p>
            </div>
          </div>
          <dl className="space-y-4 p-5 text-sm">
            <div>
              <dt className="font-medium text-slate-700">Certificate ID</dt>
              <dd className="mt-1 flex flex-wrap items-center gap-2">
                <code className="break-all rounded bg-slate-100 px-2 py-1 font-mono text-xs">{created.certificate_id}</code>
                <CopyButton value={created.certificate_id} label="certificate ID" />
                <StatusBadge status={created.certificate.effective_status} />
              </dd>
            </div>
            <div>
              <dt className="font-medium text-slate-700">Verification link (encoded in the QR code)</dt>
              <dd className="mt-1 flex flex-wrap items-center gap-2">
                <a href={created.verification_url} target="_blank" rel="noopener noreferrer" className="break-all font-mono text-xs text-brand-700 underline">
                  {created.verification_url}
                </a>
                <CopyButton value={created.verification_url} label="verification link" />
              </dd>
            </div>
            <div className="grid gap-4 sm:grid-cols-3">
              <div>
                <dt className="font-medium text-slate-700">Course</dt>
                <dd className="mt-1">{created.certificate.course_name}</dd>
              </div>
              <div>
                <dt className="font-medium text-slate-700">Issued</dt>
                <dd className="mt-1">{formatDate(created.certificate.issue_date, true)}</dd>
              </div>
              <div>
                <dt className="font-medium text-slate-700">Expires</dt>
                <dd className="mt-1">{created.certificate.expiry_date ? formatDate(created.certificate.expiry_date) : 'Never'}</dd>
              </div>
            </div>
          </dl>
          <div className="flex flex-wrap gap-2 border-t border-slate-100 p-5">
            <Button
              onClick={() => void download(created.certificate_id)}
              loading={pendingId === created.certificate_id}
              icon={<Download className="size-4" aria-hidden="true" />}
            >
              Download PDF
            </Button>
            <Link
              to={`/admin/certificates/${encodeURIComponent(created.certificate_id)}`}
              className="inline-flex h-10 items-center gap-2 rounded-lg border border-slate-300 bg-white px-4 text-sm font-medium hover:bg-slate-50"
            >
              <ExternalLink className="size-4" aria-hidden="true" />
              View details
            </Link>
            <Button
              variant="ghost"
              onClick={() => {
                setCreated(null)
                mutation.reset()
                reset({ ...issueDefaults, organization_name: readLastOrg() })
              }}
              icon={<FilePlus2 className="size-4" aria-hidden="true" />}
            >
              Issue another
            </Button>
          </div>
        </Card>
      </div>
    )
  }

  const generalError =
    mutation.isError && !(mutation.error instanceof ApiError && mutation.error.status === 422 && mutation.error.details.length > 0) ? describeError(mutation.error) : null
  const validationSummary = mutation.error instanceof ApiError && mutation.error.status === 422 && mutation.error.details.length === 0 ? describeError(mutation.error) : null

  return (
    <div>
      <PageHeader title="Issue certificate" description="Create a digitally signed PDF certificate with a verification QR code." />
      <Card className="max-w-2xl">
        <CardHeader title="Certificate details" description="Fields marked * are required." />
        <form onSubmit={handleSubmit(onSubmit)} noValidate className="space-y-5 p-5">
          <Field label="Recipient name" required error={errors.recipient_name?.message}>
            {(p) => <Input {...p} maxLength={120} autoComplete="off" {...register('recipient_name')} />}
          </Field>
          <Field label="Recipient email" optional error={errors.recipient_email?.message} hint="Stored with the record but never shown publicly or placed in the QR code.">
            {(p) => <Input {...p} type="email" maxLength={254} autoComplete="off" {...register('recipient_email')} />}
          </Field>
          <Field label="Course or achievement" required error={errors.course_name?.message}>
            {(p) => <Input {...p} maxLength={200} autoComplete="off" {...register('course_name')} />}
          </Field>
          <Field label="Issuing organization" required error={errors.organization_name?.message}>
            {(p) => <Input {...p} maxLength={200} autoComplete="organization" {...register('organization_name')} />}
          </Field>
          <div className="grid gap-5 sm:grid-cols-2">
            <div>
              <p className="mb-1.5 text-sm font-medium text-navy-900">Issue date</p>
              <p className="flex h-10 items-center gap-2 rounded-lg border border-slate-200 bg-slate-50 px-3 text-sm text-slate-600">
                <Info className="size-4 shrink-0" aria-hidden="true" />
                Set automatically when issued
              </p>
            </div>
            <Field label="Expiry date" optional error={errors.expiry_date?.message} hint="Leave empty for a certificate that does not expire.">
              {(p) => <Input {...p} type="date" {...register('expiry_date')} />}
            </Field>
          </div>

          {generalError && <Alert tone="error">{generalError}</Alert>}
          {validationSummary && <Alert tone="error">{validationSummary}</Alert>}

          <div className="flex justify-end gap-2 border-t border-slate-100 pt-4">
            <Link to="/admin/certificates" className="inline-flex h-10 items-center rounded-lg px-4 text-sm font-medium text-navy-800 hover:bg-slate-100">
              Cancel
            </Link>
            <Button type="submit" loading={mutation.isPending} icon={<FilePlus2 className="size-4" aria-hidden="true" />}>
              {mutation.isPending ? 'Issuing…' : 'Issue certificate'}
            </Button>
          </div>
        </form>
      </Card>
    </div>
  )
}
